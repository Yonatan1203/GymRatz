  /// Returns all exercises that belong to [category] (case-insensitive).
  static List<Exercise> byCategory(String category) {
    return allExercises
        .where((e) => e.category.toLowerCase() == category.toLowerCase())
        .toList();
  }

  /// Returns all exercises that use the given [type] of equipment.
  static List<Exercise> byEquipment(EquipmentType type) {
    return allExercises.where((e) => e.equipmentType == type).toList();
  }

  /// Returns the exercise with the given [id], or null if not found.
  static Exercise? byId(String id) {
    try {
      return allExercises.firstWhere((e) => e.id == id);
    } catch (_) {
      return null;
    }
  }

